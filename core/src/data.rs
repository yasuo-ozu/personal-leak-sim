pub fn era_of_year(y: i32) -> usize {
    match y {
        ..=1964 => 0,
        1965..=1979 => 1,
        1980..=1989 => 2,
        1990..=1999 => 3,
        2000..=2009 => 4,
        _ => 5,
    }
}

